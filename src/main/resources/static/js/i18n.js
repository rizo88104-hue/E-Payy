function t(key, vars) {
  var e = I18N[key];
  var s = e ? (e[LANG] != null ? e[LANG] : e.uz) : key;
  vars = vars || {};
  if (typeof s === 'object') {
    var form = 'other';
    try { form = new Intl.PluralRules(LANG).select(Number(vars.n)); } catch (x) {}
    s = s[form] || s.other;
  }
  return String(s).replace(/\{(\w+)\}/g, function (m, k) { return vars[k] != null ? vars[k] : m; });
}
