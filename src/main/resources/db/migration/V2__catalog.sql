-- V2: katalog — kategoriyalar, brendlar, mahsulotlar va ularning rasmlari.
-- Qoldiq (stock) bu yerda yo'q: u 2-bosqichdagi stocks jadvalida bo'ladi.

create table categories (
    id          bigint generated by default as identity primary key,
    name        varchar(100) not null unique,
    sort_order  integer      not null default 0
);

create table brands (
    id          bigint generated by default as identity primary key,
    name        varchar(100)  not null unique,
    -- havola uchun: kichik lotin harf, raqam va "-"
    slug        varchar(64)   not null unique,
    logo        varchar(255),
    description varchar(1000),
    country     varchar(100),
    founded     integer,
    website     varchar(255)
);

create table products (
    id            bigint generated by default as identity primary key,
    sku           varchar(64)    not null unique,
    name          varchar(255)   not null,
    description   text,
    -- restrict: mahsuloti bor kategoriya/brendni baza ham o'chirtirmaydi
    category_id   bigint         not null references categories (id) on delete restrict,
    brand_id      bigint         references brands (id) on delete restrict,
    -- narx dollarda
    price         numeric(14, 2) not null check (price >= 0),
    -- har qatorda "Nomi: qiymati"
    specs         text,
    status        varchar(16)    not null default 'DRAFT' check (status in ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
    -- optimistik blok (@Version)
    version       bigint         not null default 0,
    -- soliq: MXIK (IKPU) kodi, qadoq kodi, QQS foizi
    mxik_code     varchar(17),
    package_code  varchar(20),
    vat_percent   numeric(5, 2) check (vat_percent >= 0 and vat_percent <= 100),
    created_at    timestamp with time zone not null,
    updated_at    timestamp with time zone not null
);

create index idx_products_category on products (category_id);
create index idx_products_brand on products (brand_id);
create index idx_products_status on products (status);

create table product_images (
    id          bigint generated by default as identity primary key,
    -- mahsulot o'chsa, rasm yozuvlari ham o'chadi (fayllarni ilova o'chiradi)
    product_id  bigint       not null references products (id) on delete cascade,
    url         varchar(255) not null,
    sort_order  integer      not null default 0
);

create index idx_product_images_product on product_images (product_id, sort_order);
