-- V4: buyurtmalar. Xaridor login qilmaydi: ism, telefon va manzil buyurtmaning o'zida.

-- buyurtma raqami EP-{yil}-{NNNNNN}: yagona ketma-ketlik (yil almashganda noldan boshlanmaydi)
create sequence order_number_seq start with 1 increment by 1;

create table orders (
    id                       bigint generated by default as identity primary key,
    number                   varchar(20)    not null unique,
    customer_name            varchar(100)   not null,
    -- +998XXXXXXXXX
    phone                    varchar(13)    not null,
    address                  varchar(300)   not null,
    region                   varchar(32)    not null check (region in ('TOSHKENT_SHAHRI', 'TOSHKENT_VILOYATI',
                                 'ANDIJON', 'BUXORO', 'FARGONA', 'JIZZAX', 'XORAZM', 'NAMANGAN', 'NAVOIY',
                                 'QASHQADARYO', 'QORAQALPOGISTON', 'SAMARQAND', 'SIRDARYO', 'SURXONDARYO')),
    status                   varchar(16)    not null check (status in ('NEW', 'CONFIRMED', 'DELIVERED', 'CANCELLED')),
    pay_status               varchar(16)    not null check (pay_status in ('UNPAID', 'PAID', 'REFUND_PENDING', 'REFUNDED')),
    payment_method           varchar(8)     not null check (payment_method in ('CASH', 'PAYME', 'CLICK')),
    -- pul: dollarda va buyurtma paytidagi kurs bo'yicha so'mda qotirilgan (keyin o'zgarmaydi)
    total_usd                numeric(14, 2) not null check (total_usd >= 0),
    usd_rate                 numeric(12, 2) not null check (usd_rate > 0),
    amount_uzs               bigint         not null check (amount_uzs >= 0),
    -- to'lanmagan buyurtma shu vaqtgacha (OrderExpiryJob)
    expires_at               timestamp with time zone not null,
    paid_at                  timestamp with time zone,
    assigned_operator_id     bigint references staff (id) on delete restrict,
    operator_note            varchar(1000),
    -- xaridorning o'zi bekor qilishi uchun (keyingi bosqich): faqat xesh saqlanadi
    cancel_token_hash        varchar(100),
    cancel_token_expires_at  timestamp with time zone,
    -- bekor qilinganda qoldiq omborga qaytarildimi (2-bosqich: stocks)
    stock_returned           boolean        not null default false,
    version                  bigint         not null default 0,
    created_at               timestamp with time zone not null
);

create index idx_orders_created_at on orders (created_at);
create index idx_orders_status on orders (status);
create index idx_orders_phone on orders (phone);
create index idx_orders_operator on orders (assigned_operator_id);

-- qatorlar: mahsulot ma'lumotlari buyurtma paytidagi holatida nusxalanadi (fiskal chek uchun)
create table order_items (
    id              bigint generated by default as identity primary key,
    order_id        bigint         not null references orders (id) on delete cascade,
    -- restrict: buyurtmada ishlatilgan mahsulot o'chirilmaydi (ilova ARCHIVED qiladi)
    product_id      bigint         not null references products (id) on delete restrict,
    product_name    varchar(255)   not null,
    sku             varchar(64)    not null,
    -- bir dona narxi, tanlangan kafolat bilan
    unit_price_usd  numeric(14, 2) not null check (unit_price_usd >= 0),
    warranty_years  integer        not null check (warranty_years > 0),
    quantity        integer        not null check (quantity between 1 and 10),
    mxik_code       varchar(17),
    package_code    varchar(20)
);

create index idx_order_items_order on order_items (order_id);
create index idx_order_items_product on order_items (product_id);
