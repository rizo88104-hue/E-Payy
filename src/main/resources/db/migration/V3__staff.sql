-- V3: xodimlar (admin panelga kiradiganlar). Xaridorlar login qilmaydi.

create table staff (
    id                   bigint generated by default as identity primary key,
    -- har doim kichik harflarda saqlanadi
    username             varchar(64)  not null unique,
    -- BCrypt
    password_hash        varchar(100) not null,
    full_name            varchar(255) not null,
    phone                varchar(20),
    role                 varchar(16)  not null check (role in ('ADMIN', 'OPERATOR', 'WAREHOUSE', 'OWNER')),
    -- false — bloklangan: kira olmaydi, ochiq sessiyalari yopiladi
    active               boolean      not null default true,
    created_at           timestamp with time zone not null,
    last_login_at        timestamp with time zone,
    password_changed_at  timestamp with time zone not null
);
